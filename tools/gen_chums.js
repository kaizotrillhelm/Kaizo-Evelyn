/* gen_chums.js - builds neon/evelyn_chums_data.js (the DritchChum / Echo species table) from the owner's
   CharacterDatabase. Species are the database's CREATURE records only: no humanoid is ever a pet, and a creature
   whose look text describes a woman or girl is left out. role "nice" = Echo, role "naughty" = DritchChum.
   node tools/gen_chums.js            write the file
   node tools/gen_chums.js --check    exit 1 when the file is out of date
   Set CHUM_DB to the characters.json path when the database is somewhere else. */
"use strict";
var fs = require("fs");
var path = require("path");
var crypto = require("crypto");

var ROOT = path.resolve(__dirname, "..");
var DB = process.env.CHUM_DB || path.resolve(ROOT, "..", "CharacterDatabase", "database", "characters.json");
var OUT = path.join(ROOT, "neon", "evelyn_chums_data.js");
var WOMAN_WORDS = /\b(woman|women|girl|girls|lady|ladies|female|queen|princess|witch|maid|mermaid|nurse|humanoid)\b/i;

function clip(s, n) { s = String(s || "").replace(/\s+/g, " ").trim(); return s.length > n ? s.slice(0, n - 1).replace(/[ ,;:]+\S*$/, "") + "." : s; }

function build() {
  var raw = fs.readFileSync(DB, "utf8");
  var all = JSON.parse(raw);
  if (!Array.isArray(all)) all = all.characters || all.records;
  var rows = [], left = [];
  all.forEach(function (r) {
    if (r.kind !== "creature") return;
    var look = String(r.look || "") + " " + String(r.family || "") + " " + String(r.name || "");
    if (WOMAN_WORDS.test(look)) { left.push(r.id + " " + r.name); return; }
    rows.push({
      id: r.id,
      n: r.name,
      r: r.role === "naughty" ? "naughty" : "nice",
      sc: r.scale,
      fam: r.family,
      el: (r.elements || []).slice(0, 2),
      weak: (r.weak_to || []).slice(0, 3),
      res: (r.resists || []).slice(0, 3),
      abs: (r.absorbs || []).slice(0, 2),
      temp: clip(r.personality && r.personality.temperament, 60),
      quirk: clip(r.personality && r.personality.quirk, 110),
      voice: clip(r.personality && r.personality.voice, 90),
      eat: r.eat ? r.eat.mode : "none",
      eatHow: clip(r.eat && r.eat.how, 110),
      move: r.move ? r.move.style : "",
      home: (r.habitat && r.habitat.home_name) || ""
    });
  });
  rows.sort(function (a, b) { return a.id < b.id ? -1 : a.id > b.id ? 1 : 0; });
  var hash = crypto.createHash("sha256").update(JSON.stringify(rows)).digest("hex").slice(0, 16);
  var text = "/* evelyn_chums_data.js - GENERATED by tools/gen_chums.js from CharacterDatabase (creature records only).\n" +
    "   Do not edit by hand: change the database and run node tools/gen_chums.js.\n" +
    "   " + rows.length + " species, hash " + hash + ". role nice = Echo, role naughty = DritchChum. */\n" +
    "(function (root) {\n  \"use strict\";\n  var DATA = {\n    hash: \"" + hash + "\",\n    left: " + JSON.stringify(left) + ",\n    species: " +
    JSON.stringify(rows, null, 1).replace(/\n\s*/g, "\n").replace(/^/gm, "") + "\n  };\n" +
    "  root.EvelynChumsData = DATA;\n  if (typeof module !== \"undefined\" && module.exports) module.exports = DATA;\n" +
    "})(typeof window !== \"undefined\" ? window : global);\n";
  return { text: text, rows: rows, left: left };
}

var b = build();
if (process.argv.indexOf("--check") >= 0) {
  var cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (cur !== b.text) { console.log("evelyn_chums_data.js is out of date: run node tools/gen_chums.js"); process.exit(1); }
  console.log("evelyn_chums_data.js is current (" + b.rows.length + " species)");
} else {
  fs.writeFileSync(OUT, b.text);
  var nice = b.rows.filter(function (r) { return r.r === "nice"; }).length;
  console.log("wrote " + path.relative(ROOT, OUT) + ": " + b.rows.length + " species (" + nice + " Echoes, " + (b.rows.length - nice) + " DritchChums), left out " + b.left.length + (b.left.length ? ": " + b.left.join("; ") : ""));
}
