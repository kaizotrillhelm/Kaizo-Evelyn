/* gen_decl.js - writes basic/evelyn_decl.bi: a DECLARE line for every SUB and FUNCTION of the include files.
   FreeBASIC (and QuickBASIC) want a procedure declared before it is used; this keeps the lines in step with the definitions.
   node tools/gen_decl.js */
"use strict";
var fs = require("fs");
var path = require("path");
var dir = path.join(__dirname, "..", "basic");
var files = ["evelyn_core.bi", "evelyn_data.bi", "evelyn_io.bi", "evelyn_extra.bi"];
var out = ["' Generated by tools/gen_decl.js. Do not edit by hand.", ""];
files.forEach(function (f) {
  fs.readFileSync(path.join(dir, f), "utf8").split(/\r?\n/).forEach(function (line) {
    var m = /^(SUB|FUNCTION)\s+(.*)$/i.exec(line);
    if (m) out.push("DECLARE " + m[1].toUpperCase() + " " + m[2].replace(/\s+$/, ""));
  });
});
var text = out.join("\n") + "\n", target = path.join(dir, "evelyn_decl.bi");
if (process.argv.indexOf("--check") >= 0) {
  var same = fs.existsSync(target) && fs.readFileSync(target, "utf8") === text;
  console.log(same ? "declaration file is current" : "STALE basic/evelyn_decl.bi (run: node tools/gen_decl.js)");
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(target, text);
console.log("wrote basic/evelyn_decl.bi (" + (out.length - 2) + " declarations)");
