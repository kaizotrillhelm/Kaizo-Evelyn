/* gen_data.js - writes the data tables of the C and BASIC editions from the JavaScript reference,
   so the three editions share one copy of the starter facts, rooms and lessons.
   node tools/gen_data.js            (writes c/evelyn_data.h and basic/evelyn_data.bi) */
"use strict";
var fs = require("fs");
var path = require("path");
var E = require("../js/evelyn_core.js");

function cstr(s) {
  return "\"" + String(s).replace(/\\/g, "\\\\").replace(/"/g, "\\\"").replace(/\n/g, "\\n") + "\"";
}

/* BASIC strings have no escape for a quote: split the text at each quote and join with CHR$(34).
   Long lines are broken with "+ _" free joins: every piece stays under 200 characters. */
function bstr(s) {
  var parts = [], cur = "", i;
  function flush() { if (cur) { parts.push("\"" + cur + "\""); cur = ""; } }
  for (i = 0; i < s.length; i++) {
    var c = s.charAt(i);
    if (c === "\"") { flush(); parts.push("CHR$(34)"); }
    else if (c === "\n") { flush(); parts.push("CHR$(10)"); }
    else { cur += c; if (cur.length >= 60) flush(); }
  }
  flush();
  return parts.length ? parts.join(" + ") : "\"\"";
}

var order = ["camp", "well", "tower", "vault"];
var out = [];

/* ---------- C ---------- */
out.push("/* Generated by tools/gen_data.js from js/evelyn_core.js. Do not edit by hand. */");
out.push("#ifndef EVELYN_DATA_H");
out.push("#define EVELYN_DATA_H");
out.push("");
out.push("#define EVL_STARTER_N " + E.STARTER_FACTS.length);
out.push("static const char *const EVL_STARTER[EVL_STARTER_N][4] = {");
E.STARTER_FACTS.forEach(function (f, i) {
  out.push("  { " + [f.topic, f.cat, f.fact, f.ex].map(cstr).join(", ") + " }" + (i < E.STARTER_FACTS.length - 1 ? "," : ""));
});
out.push("};");
out.push("");
out.push("typedef struct {");
out.push("  const char *id, *title, *desc;");
out.push("  int nexits; const char *exit_dir[2]; const char *exit_room[2];");
out.push("  const char *pid, *prompt; int nkw; const char *kw[3]; const char *hint, *reward; int xp;");
out.push("} EvlRoomDef;");
out.push("#define EVL_NROOMS " + order.length);
out.push("static const EvlRoomDef EVL_ROOMS[EVL_NROOMS] = {");
order.forEach(function (id, i) {
  var r = E.ROOMS[id], p = r.puzzle;
  out.push("  { " + [cstr(id), cstr(r.title), cstr(r.desc), r.exits.length,
    "{ " + cstr(r.exits[0][0]) + ", " + (r.exits[1] ? cstr(r.exits[1][0]) : "\"\"") + " }",
    "{ " + cstr(r.exits[0][1]) + ", " + (r.exits[1] ? cstr(r.exits[1][1]) : "\"\"") + " }",
    cstr(p.id), cstr(p.prompt), p.keywords.length,
    "{ " + [0, 1, 2].map(function (j) { return p.keywords[j] ? cstr(p.keywords[j]) : "\"\""; }).join(", ") + " }",
    cstr(p.hintTopic), cstr(p.reward), p.xp].join(", ") + " }" + (i < order.length - 1 ? "," : ""));
});
out.push("};");
out.push("");
out.push("#define EVL_NLESSONS " + E.CODING_LESSONS.length);
out.push("static const char *const EVL_LESSONS[EVL_NLESSONS][3] = {");
E.CODING_LESSONS.forEach(function (l, i) {
  out.push("  { " + [l.title, l.goal, l.starter].map(cstr).join(", ") + " }" + (i < E.CODING_LESSONS.length - 1 ? "," : ""));
});
out.push("};");
out.push("");
out.push("#endif");
var CHECK = process.argv.indexOf("--check") >= 0, stale = 0;
function emit(rel, text) {
  var file = path.join(__dirname, "..", rel);
  if (CHECK) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) { console.log("STALE " + rel + " (run: node tools/gen_data.js)"); stale++; }
  } else fs.writeFileSync(file, text);
}
emit("c/evelyn_data.h", out.join("\n") + "\n");

/* ---------- BASIC ---------- */
var b = [];
b.push("' Generated by tools/gen_data.js from js/evelyn_core.js. Do not edit by hand.");
b.push("' Starter library, adventure rooms and coding lessons.");
b.push("");
b.push("SUB LoadStarterPack");
b.push("    DIM t AS STRING, c AS STRING, f AS STRING, x AS STRING, id AS INTEGER");
E.STARTER_FACTS.forEach(function (f) {
  b.push("    t = " + bstr(f.topic));
  b.push("    c = " + bstr(f.cat));
  b.push("    f = " + bstr(f.fact));
  b.push("    x = " + bstr(f.ex));
  b.push("    id = LibAdd%(t, c, f, x)");
});
b.push("END SUB");
b.push("");
b.push("SUB LoadRooms");
order.forEach(function (id, i) {
  var r = E.ROOMS[id], p = r.puzzle, k = i + 1;
  b.push("    rmId(" + k + ") = " + bstr(id));
  b.push("    rmTitle(" + k + ") = " + bstr(r.title));
  b.push("    rmDesc(" + k + ") = " + bstr(r.desc));
  b.push("    rmNEx(" + k + ") = " + r.exits.length);
  r.exits.forEach(function (e, j) {
    b.push("    rmExDir(" + k + ", " + (j + 1) + ") = " + bstr(e[0]));
    b.push("    rmExRoom(" + k + ", " + (j + 1) + ") = " + bstr(e[1]));
  });
  b.push("    rmPid(" + k + ") = " + bstr(p.id));
  b.push("    rmPrompt(" + k + ") = " + bstr(p.prompt));
  b.push("    rmNKw(" + k + ") = " + p.keywords.length);
  p.keywords.forEach(function (w, j) { b.push("    rmKw(" + k + ", " + (j + 1) + ") = " + bstr(w)); });
  b.push("    rmHint(" + k + ") = " + bstr(p.hintTopic));
  b.push("    rmReward(" + k + ") = " + bstr(p.reward));
  b.push("    rmXp(" + k + ") = " + p.xp);
});
b.push("END SUB");
b.push("");
b.push("FUNCTION LessonStarter$ (n AS INTEGER)");
b.push("    DIM s AS STRING");
b.push("    s = \"\"");
E.CODING_LESSONS.forEach(function (l, i) {
  b.push("    IF n = " + (i + 1) + " THEN s = " + bstr(l.starter));
});
b.push("    LessonStarter$ = s");
b.push("END FUNCTION");
emit("basic/evelyn_data.bi", b.join("\n") + "\n");
if (CHECK) {
  console.log(stale ? stale + " generated file(s) out of date" : "generated data files are current");
  process.exit(stale ? 1 : 0);
}
console.log("wrote c/evelyn_data.h and basic/evelyn_data.bi");
